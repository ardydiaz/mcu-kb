import {Router} from 'express';
import authRoutes from './auth.routes.js';
import publicRoutes from './public.routes.js';
import documentsRoutes from './documents.routes.js';
import systemsRoutes from './systems.routes.js';
import usersRoutes from './users.routes.js';
import categoriesRoutes from './categories.routes.js';
import departmentsRoutes from './departments.routes.js';
import knowledgeRoutes from './knowledge.routes.js';
import landingPagesRoutes from './landing-pages.routes.js';
import announcementsRoutes from './announcements.routes.js';
import notificationsRoutes from './notifications.routes.js';
import analyticsRoutes from './analytics.routes.js';
import DashboardController from '../controllers/DashboardController.js';
import auth from '../middleware/authMiddleware.js';
import {allowRoles} from '../middleware/roleMiddleware.js';
import asyncHandler from '../utils/asyncHandler.js';

const router=Router();
router.use('/auth',authRoutes);
router.use('/public',publicRoutes);
router.use(auth);
router.use('/documents',documentsRoutes);
router.use('/systems',systemsRoutes);
router.use('/users',usersRoutes);
router.use('/categories',categoriesRoutes);
router.use('/departments',departmentsRoutes);
router.use('/knowledge',knowledgeRoutes);
router.use('/landing-pages',landingPagesRoutes);
router.use('/announcements',announcementsRoutes);
router.use('/notifications',notificationsRoutes);
router.use('/analytics',analyticsRoutes);
router.get('/dashboard',allowRoles(1,2),asyncHandler(DashboardController.index));
export default router;
